package io.smallrye.ffm.maven;

import static java.lang.constant.ConstantDescs.*;
import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;

import java.lang.constant.ClassDesc;
import java.lang.constant.MethodTypeDesc;
import java.lang.reflect.Field;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;

import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import io.smallrye.classfile.Annotation;
import io.smallrye.classfile.AnnotationElement;
import io.smallrye.classfile.AnnotationValue;
import io.smallrye.classfile.ClassFile;
import io.smallrye.classfile.attribute.RuntimeInvisibleAnnotationsAttribute;
import io.smallrye.classfile.attribute.RuntimeInvisibleParameterAnnotationsAttribute;

/**
 * The transform goal registers the downcall shapes it links in a native image metadata file.
 */
public final class NativeMetadataTest {
    private static final ClassDesc CD_MemorySegment = ClassDesc.of("java.lang.foreign.MemorySegment");
    private static final ClassDesc CD_ErrnoConsumer = ClassDesc.of("io.smallrye.ffm.ErrnoConsumer");
    private static final ClassDesc CD_AsType = ClassDesc.of("io.smallrye.ffm.AsType");
    private static final Annotation LINK = Annotation.of(ClassDesc.of("io.smallrye.ffm.Link"));
    private static final Annotation CRITICAL = Annotation.of(ClassDesc.of("io.smallrye.ffm.Critical"));
    private static final Annotation VARIADIC = Annotation.of(ClassDesc.of("io.smallrye.ffm.Variadic"));

    private static final String EXPECTED = """
            {
              "comment": "Generated by smallrye-ffm-maven-plugin for the downcalls linked by this module",
              "foreign": {
                "downcalls": [
                  {"returnType": "jdouble", "parameterTypes": ["jdouble"], "options": {"captureCallState": true}},
                  {"returnType": "jint", "parameterTypes": ["jbyte"]},
                  {"returnType": "jint", "parameterTypes": ["jint"]},
                  {"returnType": "jint", "parameterTypes": ["void*", "jint", "jdouble", "void*"], "options": {"firstVariadicArg": 1}},
                  {"returnType": "jint", "parameterTypes": ["void*", "void*", "jint", "void*"], "options": {"firstVariadicArg": 4}},
                  {"returnType": "jlong", "parameterTypes": ["void*"], "options": {"critical": {"allowHeapAccess": false}}},
                  {"returnType": "long", "parameterTypes": ["long"]},
                  {"returnType": "void", "parameterTypes": []}
                ]
              }
            }
            """;

    @TempDir
    Path dir;

    public NativeMetadataTest() {
    }

    @Test
    public void testDowncallsAreRegistered() throws Exception {
        writeNatives();
        transform(false);
        assertEquals(EXPECTED, Files.readString(metadataFile()));
    }

    @Test
    public void testAlreadyTransformedClassesAreRegistered() throws Exception {
        writeNatives();
        transform(false);
        Files.delete(metadataFile());
        // the classes are no longer native, as after an incremental build
        transform(false);
        assertEquals(EXPECTED, Files.readString(metadataFile()));
    }

    @Test
    public void testSkipNativeMetadata() throws Exception {
        writeNatives();
        transform(true);
        assertFalse(Files.exists(metadataFile()));
    }

    @Test
    public void testNoDowncallsNoFile() throws Exception {
        Files.write(dir.resolve("Plain.class"), ClassFile.of().build(ClassDesc.of("Plain"), zb -> {
        }));
        transform(false);
        assertFalse(Files.exists(metadataFile()));
    }

    @Test
    public void testCharIsRegisteredForBothRepresentations() {
        assertEquals(List.of(
                "{\"returnType\": \"jint\", \"parameterTypes\": [\"jbyte\", \"jbyte\"]}",
                "{\"returnType\": \"jint\", \"parameterTypes\": [\"jint\", \"jbyte\"]}"),
                NativeMetadata.entries("(csc)uc"));
    }

    private Path metadataFile() {
        return dir.resolve("META-INF/native-image/org.example/natives/smallrye-ffm/reachability-metadata.json");
    }

    private void transform(boolean skip) throws Exception {
        TransformMojo mojo = new TransformMojo();
        set(mojo, TransformMojo.class, "classesDirectory", dir.toFile());
        set(mojo, AbstractTransformMojo.class, "groupId", "org.example");
        set(mojo, AbstractTransformMojo.class, "artifactId", "natives");
        set(mojo, AbstractTransformMojo.class, "skipNativeMetadata", skip);
        mojo.execute();
    }

    private static void set(Object target, Class<?> owner, String name, Object value) throws Exception {
        Field field = owner.getDeclaredField(name);
        field.setAccessible(true);
        field.set(target, value);
    }

    /**
     * Write a class with some {@code @Link} methods, as {@code javac} would compile them.
     */
    private void writeNatives() throws Exception {
        Path pkg = Files.createDirectories(dir.resolve("org/example"));
        byte[] bytes = ClassFile.of().build(ClassDesc.of("org.example.Natives"), zb -> {
            // static native int abs(int value);
            method(zb, "abs", MethodTypeDesc.of(CD_int, CD_int), List.of(LINK), List.of());
            // static native int abs2(int value); (same shape)
            method(zb, "abs2", MethodTypeDesc.of(CD_int, CD_int), List.of(LINK), List.of());
            // static native void sync();
            method(zb, "sync", MethodTypeDesc.of(CD_void), List.of(LINK), List.of());
            // static native int printf(String format, @Variadic int a, double b, MemorySegment end);
            method(zb, "printf", MethodTypeDesc.of(CD_int, CD_String, CD_int, CD_double, CD_MemorySegment), List.of(LINK),
                    List.of(List.of(), List.of(VARIADIC), List.of(), List.of()));
            // @Variadic static native int snprintf(MemorySegment buf, String format, int n, MemorySegment arg);
            // (variadic marker at the end of the fixed arguments)
            method(zb, "snprintf", MethodTypeDesc.of(CD_int, CD_MemorySegment, CD_String, CD_int, CD_MemorySegment),
                    List.of(LINK, VARIADIC), List.of());
            // @Critical static native @As(size_t) long strlen(byte[] s);
            method(zb, "strlen", MethodTypeDesc.of(CD_long, CD_byte.arrayType()),
                    List.of(LINK, CRITICAL, as("size_t")), List.of());
            // static native double log(double value, ErrnoConsumer errno);
            method(zb, "log", MethodTypeDesc.of(CD_double, CD_double, CD_ErrnoConsumer), List.of(LINK), List.of());
            // static native @As(stdc_long) long labs(@As(stdc_long) long value);
            method(zb, "labs", MethodTypeDesc.of(CD_long, CD_long), List.of(LINK, as("stdc_long")),
                    List.of(List.of(as("stdc_long"))));
            // static native int toByte(byte c); (default s8)
            method(zb, "toByte", MethodTypeDesc.of(CD_int, CD_byte), List.of(LINK), List.of());
        });
        Files.write(pkg.resolve("Natives.class"), bytes);
    }

    private static Annotation as(String type) {
        return Annotation.of(ClassDesc.of("io.smallrye.ffm.As"),
                AnnotationElement.of("value", AnnotationValue.ofEnum(CD_AsType, type)));
    }

    private static void method(io.smallrye.classfile.ClassBuilder zb, String name, MethodTypeDesc type,
            List<Annotation> annotations, List<List<Annotation>> paramAnnotations) {
        zb.withMethod(name, type, ClassFile.ACC_STATIC | ClassFile.ACC_NATIVE, mb -> {
            mb.with(RuntimeInvisibleAnnotationsAttribute.of(annotations));
            if (!paramAnnotations.isEmpty()) {
                mb.with(RuntimeInvisibleParameterAnnotationsAttribute.of(new ArrayList<>(paramAnnotations)));
            }
        });
    }
}
